#!/usr/bin/env python3
"""Generate the Kotlin device catalog from DeviceFaker's MIT-licensed TOML templates."""

import argparse
import re
import zipfile
from pathlib import Path


HEADER = re.compile(r'^\[templates\.(?:"((?:[^"\\]|\\.)*)"|([^\]]+))\]\s*$')
VALUE = re.compile(r'^(manufacturer|brand|model|device|product)\s*=\s*"(.*)"\s*$')
LEGACY_NAMES = {
    "Galaxy Z Fold8", "Galaxy Z Fold8 Ultra", "Galaxy Z Fold7", "Galaxy Z Fold6",
    "Galaxy Z Fold5", "Galaxy Z Flip8", "Galaxy Z Flip7", "Galaxy Z Flip6",
    "Galaxy Z Flip5", "Galaxy S26 Ultra", "Galaxy S26", "Galaxy S25 Ultra",
    "Galaxy S25", "Galaxy S24 Ultra",
}


def decode_toml_string(value: str) -> str:
    return bytes(value, "utf-8").decode("unicode_escape") if "\\" in value else value


def kotlin_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def source_group(name: str) -> str:
    parts = Path(name).parts
    return parts[-2] if len(parts) >= 2 else "更多机型"


def parse_template(name: str, content: str):
    title = None
    values = {}
    for line in content.splitlines():
        header = HEADER.match(line.strip())
        if header:
            title = decode_toml_string(header.group(1) or header.group(2).strip())
            continue
        match = VALUE.match(line.strip())
        if match:
            values[match.group(1)] = decode_toml_string(match.group(2)).strip()
    if not title:
        return None
    model = values.get("model", "")
    device = values.get("device", "") or values.get("product", "") or model
    product = values.get("product", "") or device
    if not all((values.get("manufacturer"), values.get("brand"), model, device, product)):
        return None
    return {
        "name": title,
        "manufacturer": values["manufacturer"],
        "brand": values["brand"],
        "model": model,
        "device": device,
        "product": product,
        "family": source_group(name),
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("source_zip", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()

    candidates = {}
    with zipfile.ZipFile(args.source_zip) as archive:
        names = sorted(
            n for n in archive.namelist()
            if n.startswith("config/templates/") and n.endswith(".toml")
        )
        for name in names:
            item = parse_template(name, archive.read(name).decode("utf-8"))
            if not item or item["name"] in LEGACY_NAMES:
                continue
            score = sum(bool(item[key]) for key in ("manufacturer", "brand", "model", "device", "product"))
            current = candidates.get(item["name"])
            if current is None or score > current[0]:
                candidates[item["name"]] = (score, item)

    items = [entry[1] for entry in candidates.values()]
    items.sort(key=lambda x: (x["family"].casefold(), x["name"].casefold()))
    lines = [
        "package com.nilou.cscchanger.core",
        "",
        "/** Generated by scripts/import_devicefaker_templates.py. Do not edit manually. */",
        "internal object GeneratedDeviceProfiles {",
        "    val ALL: List<DeviceProfile> = listOf(",
    ]
    for item in items:
        lines.extend([
            "        DeviceProfile(",
            f"            name = {kotlin_string(item['name'])},",
            f"            model = {kotlin_string(item['model'])},",
            f"            device = {kotlin_string(item['device'])},",
            f"            productName = {kotlin_string(item['product'])},",
            f"            family = {kotlin_string(item['family'])},",
            f"            brand = {kotlin_string(item['brand'])},",
            f"            manufacturer = {kotlin_string(item['manufacturer'])},",
            "        ),",
        ])
    lines.extend(["    )", "}", ""])
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {len(items)} unique compatible profiles: {args.output}")


if __name__ == "__main__":
    main()
